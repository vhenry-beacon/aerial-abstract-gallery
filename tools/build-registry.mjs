// Bundles every clients/<slug>/client.json + manifest.json into one module
// that the functions and edge functions import. Runs as the Netlify build command.
import { readdirSync, readFileSync, existsSync, writeFileSync } from "node:fs";
import { join, dirname } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const clientsDir = join(root, "clients");
const registry = {};

for (const slug of readdirSync(clientsDir)) {
  const cfgPath = join(clientsDir, slug, "client.json");
  if (!existsSync(cfgPath)) continue;
  const client = JSON.parse(readFileSync(cfgPath, "utf8"));
  const manPath = join(clientsDir, slug, "manifest.json");
  const manifest = existsSync(manPath) ? JSON.parse(readFileSync(manPath, "utf8")) : { items: [] };
  if (client.slug !== slug) throw new Error(`client.json slug "${client.slug}" must match folder "${slug}"`);
  const ids = new Set();
  for (const it of manifest.items) {
    if (ids.has(it.id)) throw new Error(`${slug}: duplicate item id ${it.id}`);
    ids.add(it.id);
  }
  registry[slug] = { ...client, items: manifest.items };
}

writeFileSync(
  join(root, "lib", "registry.generated.mjs"),
  "// GENERATED by tools/build-registry.mjs — do not edit by hand.\nexport default " +
    JSON.stringify(registry, null, 2) + ";\n"
);
console.log(`registry: ${Object.keys(registry).length} client(s): ${Object.keys(registry).join(", ")}`);
